"""Bounded research-workflow service (CREA Stage 7.2).

A finite task DAG over a research session. The task list comes from an explicit
built-in template or an explicit user-supplied list -- never generated by a
model. Tasks are executed **one at a time, on explicit request**; the service
orchestrates and the executor does the work. It never loops, never generates
tasks, and the agent cannot change it.

Name note (why `TaskWorkflow`, not `ResearchWorkflow`): a `ResearchWorkflow`
(the single-run pipeline) and a `ResearchTask` (one research question) already
exist. This is a different object: a task DAG you run one task at a time.
"""

from __future__ import annotations

from crea.core.errors import ResearchWorkflowError
from crea.core.ids import content_hash
from crea.core.models.research_study import StudyEventType
from crea.core.models.task_workflow import (
    MAX_TASKS,
    MAX_TASK_RETRIES,
    MAX_WORKFLOW_DEPTH,
    SATISFIED,
    TaskStatus,
    TaskType,
    TaskWorkflow,
    TaskWorkflowDetail,
    WorkflowStatus,
    WorkflowTask,
)
from crea.core.provenance import utc_now_iso


def _spec(key, task_type, title, deps=(), inputs=None):
    return {"key": key, "task_type": task_type, "title": title,
            "deps": list(deps), "inputs": dict(inputs or {})}


#: Built-in templates. A callable takes the create params and returns task
#: specs. Deliberately few and fixed: the task set is never model-authored.
TEMPLATES = {
    "molecule_modification": lambda p: [
        _spec("search", TaskType.TRANSFORMATION_SEARCH,
              "Search transformations for the substrate",
              inputs={"substrate": p.get("substrate", ""),
                      "target": p.get("target", "")}),
        _spec("compare", TaskType.REACTION_COMPARISON,
              "Compare the candidate reactions", deps=("search",),
              inputs={"reaction_template_ids": p.get("reaction_template_ids", []),
                      "substrate": p.get("substrate", ""),
                      "target": p.get("target", "")}),
        _spec("evidence", TaskType.EVIDENCE_REVIEW,
              "Review the evidence behind a reaction", deps=("search",),
              inputs={"reaction_template_id": p.get("reaction_template_id", "")}),
        _spec("modify", TaskType.MODIFICATION_ANALYSIS,
              "Analyse the requested modification", deps=("evidence",),
              inputs={"substrate": p.get("substrate", ""),
                      "query": p.get("query", "")}),
    ],
    "route_study": lambda p: [
        _spec("search", TaskType.TRANSFORMATION_SEARCH,
              "Search transformations for the start molecule",
              inputs={"substrate": p.get("start", ""), "target": p.get("target", "")}),
        _spec("route", TaskType.ROUTE_EXPLORATION,
              "Explore deterministic routes", deps=("search",),
              inputs={"start": p.get("start", ""), "target": p.get("target", "")}),
        _spec("reason", TaskType.ROUTE_REASONING,
              "Reason about the explored routes", deps=("route",),
              inputs={"start": p.get("start", ""), "target": p.get("target", ""),
                      "query": p.get("query", "compare the routes")}),
    ],
    "evidence_review": lambda p: [
        _spec("evidence", TaskType.EVIDENCE_REVIEW,
              "Review the evidence behind a reaction",
              inputs={"reaction_template_id": p.get("reaction_template_id", "")}),
    ],
}


class TaskWorkflowService:
    """Create, run and read back a bounded research workflow."""

    def __init__(self, kb, executor) -> None:
        self._kb = kb
        self._executor = executor

    # -- create -------------------------------------------------------------

    def create(self, study_id: str, *, template: str = "", tasks=None,
               title: str = "", params=None) -> TaskWorkflow:
        from crea.services.research_study import ResearchStudyService

        ResearchStudyService(self._kb).get(study_id)  # STUDY_NOT_FOUND if absent
        params = dict(params or {})

        if template:
            if template not in TEMPLATES:
                raise ResearchWorkflowError(
                    "INVALID_INPUT", f"unknown workflow template {template!r}")
            specs = TEMPLATES[template](params)
        elif tasks:
            specs = [dict(t) for t in tasks]
        else:
            raise ResearchWorkflowError(
                "INVALID_INPUT", "a workflow needs a template or an explicit task list")

        if len(specs) > MAX_TASKS:
            raise ResearchWorkflowError(
                "WORKFLOW_LIMIT_REACHED",
                f"a workflow may hold at most {MAX_TASKS} tasks")

        workflow_id = "wf-" + content_hash(
            f"{study_id}|{template}|{title}|{utc_now_iso()}", 16)
        workflow = TaskWorkflow(
            workflow_id=workflow_id, study_id=study_id, template=template,
            title=title or (template or "Workflow"), status=WorkflowStatus.READY)
        self._kb.save_workflow(workflow)

        specs_by_key = {s.get("key"): s for s in specs if s.get("key")}
        tasks_out: list[WorkflowTask] = []
        for spec in specs:
            key = spec.get("key")
            if not key:
                raise ResearchWorkflowError(
                    "INVALID_INPUT", "every task needs a key")
            deps = list(spec.get("deps") or [])
            for dep in deps:
                if dep not in specs_by_key:
                    raise ResearchWorkflowError(
                        "INVALID_INPUT", f"task {key!r} depends on unknown "
                        f"task {dep!r}")
            tasks_out.append(WorkflowTask(
                task_id=self._task_id(workflow_id, key),
                workflow_id=workflow_id, task_type=spec["task_type"],
                title=spec.get("title", ""), input_refs=dict(spec.get("inputs") or {}),
                depends_on=[self._task_id(workflow_id, d) for d in deps]))

        self._check_graph(tasks_out)
        for task in tasks_out:
            self._kb.save_task(task)
            self._event(study_id, StudyEventType.TASK_CREATED,
                        summary=f"{task.task_type.value}: {task.title}")
        self._event(study_id, StudyEventType.WORKFLOW_CREATED,
                    summary=f"workflow created ({len(tasks_out)} tasks)")
        self._refresh_ready(workflow)
        return self._kb.get_workflow(workflow_id)

    @staticmethod
    def _task_id(workflow_id: str, key: str) -> str:
        return f"{workflow_id}::{key}"

    def _check_graph(self, tasks: list[WorkflowTask]) -> None:
        """Reject a cycle; enforce depth and count bounds."""
        by_id = {t.task_id: t for t in tasks}
        for task in tasks:
            for dep in task.depends_on:
                if dep not in by_id:
                    raise ResearchWorkflowError(
                        "INVALID_INPUT", f"task {task.task_id!r} depends on a task "
                        f"outside this workflow")

        WHITE, GREY, BLACK = 0, 1, 2
        colour = {t.task_id: WHITE for t in tasks}
        depth: dict[str, int] = {}

        def visit(task_id: str, stack: list[str]) -> int:
            if colour[task_id] == GREY:
                raise ResearchWorkflowError(
                    "WORKFLOW_CYCLE",
                    "task dependencies form a cycle: " + " -> ".join(stack + [task_id]))
            if colour[task_id] == BLACK:
                return depth[task_id]
            colour[task_id] = GREY
            best = 0
            for dep in by_id[task_id].depends_on:
                best = max(best, visit(dep, stack + [task_id]))
            colour[task_id] = BLACK
            depth[task_id] = best + 1
            return depth[task_id]

        longest = max((visit(t.task_id, []) for t in tasks), default=0)
        if longest > MAX_WORKFLOW_DEPTH:
            raise ResearchWorkflowError(
                "WORKFLOW_LIMIT_REACHED",
                f"dependency depth {longest} exceeds {MAX_WORKFLOW_DEPTH}")

    # -- reads --------------------------------------------------------------

    def get(self, workflow_id: str) -> TaskWorkflow:
        workflow = self._kb.get_workflow(workflow_id)
        if workflow is None:
            raise ResearchWorkflowError(
                "WORKFLOW_NOT_FOUND", f"no workflow {workflow_id!r}")
        return workflow

    def detail(self, workflow_id: str) -> TaskWorkflowDetail:
        detail = self._kb.get_workflow_detail(workflow_id)
        if detail is None:
            raise ResearchWorkflowError(
                "WORKFLOW_NOT_FOUND", f"no workflow {workflow_id!r}")
        return detail

    def list(self, study_id: str) -> list[TaskWorkflow]:
        return self._kb.list_workflows(study_id)

    def ready_tasks(self, workflow_id: str) -> list[WorkflowTask]:
        self.get(workflow_id)
        self._refresh_ready(self._kb.get_workflow(workflow_id))
        return [t for t in self._kb.list_tasks(workflow_id)
                if t.status is TaskStatus.READY]

    # -- lifecycle ----------------------------------------------------------

    def start(self, workflow_id: str) -> TaskWorkflow:
        workflow = self._require_state(workflow_id, {WorkflowStatus.READY,
                                                     WorkflowStatus.BLOCKED})
        workflow.status = WorkflowStatus.RUNNING
        self._save(workflow)
        self._event(workflow.study_id, StudyEventType.WORKFLOW_STARTED,
                    summary="workflow started")
        self._refresh_ready(workflow)
        return self._kb.get_workflow(workflow_id)

    def pause(self, workflow_id: str) -> TaskWorkflow:
        workflow = self._require_state(workflow_id, {WorkflowStatus.RUNNING})
        workflow.status = WorkflowStatus.PAUSED
        self._save(workflow)
        self._event(workflow.study_id, StudyEventType.WORKFLOW_PAUSED,
                    summary="workflow paused")
        return self._kb.get_workflow(workflow_id)

    def resume(self, workflow_id: str) -> TaskWorkflow:
        workflow = self._require_state(workflow_id, {WorkflowStatus.PAUSED})
        workflow.status = WorkflowStatus.RUNNING
        self._save(workflow)
        self._event(workflow.study_id, StudyEventType.WORKFLOW_RESUMED,
                    summary="workflow resumed")
        self._refresh_ready(workflow)
        return self._kb.get_workflow(workflow_id)

    def cancel(self, workflow_id: str) -> TaskWorkflow:
        workflow = self._require_state(workflow_id, {
            WorkflowStatus.READY, WorkflowStatus.RUNNING,
            WorkflowStatus.PAUSED, WorkflowStatus.BLOCKED})
        workflow.status = WorkflowStatus.CANCELLED
        self._save(workflow)
        for task in self._kb.list_tasks(workflow_id):
            if task.status not in SATISFIED and task.status is not TaskStatus.FAILED:
                task.status = TaskStatus.CANCELLED
                self._kb.save_task(task)
        self._event(workflow.study_id, StudyEventType.WORKFLOW_CANCELLED,
                    summary="workflow cancelled")
        return self._kb.get_workflow(workflow_id)

    # -- tasks --------------------------------------------------------------

    def execute_task(self, workflow_id: str, task_id: str) -> WorkflowTask:
        """Run one task, on explicit request, and store its artifact."""
        workflow = self._require_state(workflow_id, {WorkflowStatus.RUNNING})
        task = self._get_task(workflow_id, task_id)
        if task.status in (TaskStatus.COMPLETED, TaskStatus.SKIPPED):
            return task
        if task.status is TaskStatus.FAILED and task.attempt_count >= MAX_TASK_RETRIES:
            raise ResearchWorkflowError(
                "TASK_RETRY_LIMIT", f"task {task_id!r} has been retried "
                f"{task.attempt_count} times")
        satisfied = {t.task_id for t in self._kb.list_tasks(workflow_id)
                     if t.status in SATISFIED}
        if not set(task.depends_on) <= satisfied:
            raise ResearchWorkflowError(
                "TASK_NOT_READY",
                f"task {task_id!r} has unfinished dependencies")

        task.attempt_count += 1
        task.status = TaskStatus.RUNNING
        task.updated_at = utc_now_iso()
        self._kb.save_task(task)
        self._event(workflow.study_id, StudyEventType.TASK_STARTED,
                    summary=f"{task.task_type.value} started")

        outcome = self._executor.run(task)
        if outcome.status == "completed":
            from crea.services.research_study import ResearchStudyService

            artifact = ResearchStudyService(self._kb).add_artifact(
                workflow.study_id, outcome.artifact_type,
                outcome.content, label=task.title)
            task.output_artifact_ids = [artifact.artifact_id]
            task.status = TaskStatus.COMPLETED
            task.error = ""
            self._kb.save_task(task)
            self._event(workflow.study_id, StudyEventType.TASK_COMPLETED,
                        summary=f"{task.task_type.value} completed",
                        artifact_id=artifact.artifact_id)
        elif outcome.status == "blocked":
            task.status = TaskStatus.BLOCKED
            task.error = outcome.error
            self._kb.save_task(task)
            self._event(workflow.study_id, StudyEventType.TASK_BLOCKED,
                        summary=f"{task.task_type.value} blocked: {outcome.error}")
        else:
            task.status = TaskStatus.FAILED
            task.error = outcome.error
            self._kb.save_task(task)
            self._event(workflow.study_id, StudyEventType.TASK_FAILED,
                        summary=f"{task.task_type.value} failed: {outcome.error}")

        self._recompute_workflow(workflow)
        return self._kb.get_task(task_id)

    def skip_task(self, workflow_id: str, task_id: str, reason: str = "") -> WorkflowTask:
        self.get(workflow_id)
        task = self._get_task(workflow_id, task_id)
        task.status = TaskStatus.SKIPPED
        task.error = reason
        task.updated_at = utc_now_iso()
        self._kb.save_task(task)
        workflow = self._kb.get_workflow(workflow_id)
        self._event(workflow.study_id, StudyEventType.TASK_SKIPPED,
                    summary=f"{task.task_type.value} skipped: {reason}")
        self._refresh_ready(workflow)
        self._recompute_workflow(workflow)
        return self._kb.get_task(task_id)

    # -- helpers ------------------------------------------------------------

    def _require_state(self, workflow_id: str,
                       allowed: set[WorkflowStatus]) -> TaskWorkflow:
        workflow = self.get(workflow_id)
        if workflow.status not in allowed:
            raise ResearchWorkflowError(
                "INVALID_WORKFLOW_STATE",
                f"workflow is {workflow.status.value}; expected one of "
                f"{sorted(s.value for s in allowed)}")
        return workflow

    def _get_task(self, workflow_id: str, task_id: str) -> WorkflowTask:
        task = self._kb.get_task(task_id)
        if task is None or task.workflow_id != workflow_id:
            raise ResearchWorkflowError(
                "TASK_NOT_FOUND", f"no task {task_id!r} in workflow {workflow_id!r}")
        return task

    def _refresh_ready(self, workflow: TaskWorkflow) -> None:
        tasks = self._kb.list_tasks(workflow.workflow_id)
        satisfied = {t.task_id for t in tasks if t.status in SATISFIED}
        for task in tasks:
            if task.status is not TaskStatus.PENDING:
                continue
            if set(task.depends_on) <= satisfied:
                task.status = TaskStatus.READY
                task.updated_at = utc_now_iso()
                self._kb.save_task(task)

    def _recompute_workflow(self, workflow: TaskWorkflow) -> None:
        tasks = self._kb.list_tasks(workflow.workflow_id)
        if not tasks:
            return
        statuses = {t.status for t in tasks}
        if all(t.status in SATISFIED for t in tasks):
            workflow.status = WorkflowStatus.COMPLETED
            self._save(workflow)
            self._event(workflow.study_id, StudyEventType.WORKFLOW_COMPLETED,
                        summary="workflow completed")
        elif statuses & {TaskStatus.FAILED, TaskStatus.BLOCKED}:
            workflow.status = WorkflowStatus.BLOCKED
            self._save(workflow)
            self._event(workflow.study_id, StudyEventType.WORKFLOW_BLOCKED,
                        summary="workflow blocked by a failed or blocked task")

    def _save(self, workflow: TaskWorkflow) -> None:
        workflow.updated_at = utc_now_iso()
        self._kb.save_workflow(workflow)

    def _event(self, study_id: str, event_type: StudyEventType,
               *, summary: str = "", artifact_id: str = "") -> None:
        from crea.services.research_study import ResearchStudyService

        ResearchStudyService(self._kb).append_event(
            study_id, event_type, summary=summary, artifact_id=artifact_id)


__all__ = ["TEMPLATES", "TaskWorkflowService"]
