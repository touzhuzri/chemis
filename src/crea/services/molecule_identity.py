"""The one place a SMILES becomes its standard chemical identity (Stage 2.2).

Standard InChI / Standard InChIKey are generated by the existing `normalize`
(the single RDKit home), never re-implemented here (§5/§24). This service is
the stable, named entry point that turns a SMILES into a `MoleculeIdentity`
and types a bad input as `INVALID_MOLECULE`.
"""

from __future__ import annotations

from crea.core.errors import MoleculeLibraryError
from crea.core.models.entity import identity_key
from crea.core.models.molecule_identity import MoleculeIdentity


class MoleculeIdentityService:
    """Compute the standard chemical identity of a SMILES."""

    def identity(self, smiles: str) -> MoleculeIdentity:
        from crea.chem.normalize import NormalizationError, normalize

        try:
            molecule = normalize(smiles)
        except NormalizationError as exc:
            raise MoleculeLibraryError(
                "INVALID_MOLECULE",
                f"the SMILES is not a parseable structure: {exc}") from exc

        d = molecule.descriptors
        return MoleculeIdentity(
            standard_inchi=molecule.inchi,
            standard_inchikey=molecule.inchikey,
            canonical_smiles=molecule.canonical_smiles,
            molecular_formula=d.molecular_formula,
            molecular_weight=d.mol_wt,
            formal_charge=d.net_charge,
            identity_key=identity_key(molecule.inchi),
        )


__all__ = ["MoleculeIdentityService"]
