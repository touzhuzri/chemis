def test_an_oversized_file_is_refused_before_it_is_read(service, workspace, monkeypatch):
    import crea.core.policy.document as policy

    monkeypatch.setattr(policy, "DEFAULT_MAX_DOCUMENT_BYTES", 10)
    monkeypatch.setattr(policy, "max_document_bytes", lambda: 10, raising=False)
    path = workspace / "big.pdf"
    path.write_bytes(pdfs.make_pdf(pdfs.SINGLE_PAGE))
    with pytest.raises(DocumentError) as exc:
        service.ingest(path)
    assert exc.value.kind is DocumentErrorKind.TOO_LARGE
    assert "resource-protection limit" in str(exc.value)


def test_the_size_limit_is_a_single_named_policy_value():
    from crea.core.policy import document as policy

    assert policy.DEFAULT_MAX_DOCUMENT_BYTES == 100 * 1024 * 1024
    assert policy.PDF_SIGNATURE == b"%PDF-"


