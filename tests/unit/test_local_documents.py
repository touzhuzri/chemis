def test_match_types_are_deterministic():
    mixed = "Sodium Hydride was used. Later SODIUM HYDRIDE again."
    assert [m for _, m in find_occurrences(mixed, "Sodium Hydride")] == \
        [MatchType.SUBSTRING]
    # not present verbatim in that casing, so it degrades exactly one step
    assert [m for _, m in find_occurrences(mixed, "sodium hydride")] == \
        [MatchType.CASE_INSENSITIVE] * 2
    # word order differs, so only token matching can find it -- and the tokens
    # of a single occurrence collapse into one hit rather than one per token
    assert [m for _, m in find_occurrences(mixed, "hydride sodium")] == \
        [MatchType.TOKEN] * 2
    assert find_occurrences(mixed, "platinum") == []
    assert find_occurrences(mixed, "   ") == []


