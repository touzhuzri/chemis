def test_a_whole_document_is_never_shredded_into_evidence(service, workspace):
    """Query-driven, not bulk.

    A 30-page paper must not produce 30,000 citations. Evidence appears where
    a query lands, and nowhere else.
    """
    parsed = ingest(service, workspace, "multi.pdf", pdfs.MULTI_PAGE)
    hits = search_document(parsed, "heated at 110 C")
    assert len(hits) == 1
    assert hits[0].page == 3
    # a query matching nothing produces nothing, not "everything"
    assert search_document(parsed, "osmium catalysis") == []


def test_retrieval_locates_text_and_does_not_answer_questions(service, workspace):
    """It finds passages. It does not read them.

    A question-shaped query can still match a word inside it -- "reaction"
    appears in the fixture -- and what comes back is the surrounding passage,
    not an extracted catalyst. The distinction is the whole boundary: this
    stack locates, and understanding is a later phase.
    """
    parsed = ingest(service, workspace, "single.pdf", pdfs.SINGLE_PAGE)
    hits = search_document(parsed, "which catalyst did this reaction use")

    for hit in hits:
        # what it returns is a quote, never an answer
        assert hit.evidence.raw_quote
        assert "catalyst" not in hit.evidence.raw_quote.lower()
        # and nothing anywhere claims to have extracted a catalyst
        assert "catalyst" not in str(hit.evidence.model_dump()).lower()             or hit.evidence.raw_quote.lower().find("catalyst") < 0

    # a query with no matching word finds nothing rather than everything
    assert search_document(parsed, "osmium catalysis") == []


