def test_the_evidence_chain_closes(service, workspace):
    parsed = ingest(service, workspace, "single.pdf", pdfs.SINGLE_PAGE)
    hits = search_document(parsed, "Yield 82%")
    assert hits
    evidence = hits[0].evidence

    claim = Claim.build(
        "claim-1",
        "The reported procedure states a yield of 82%.",
        "experimental_fact",
        [evidence.evidence_id],
    )
    # hand-built, by the test. No model was asked for a conclusion, and none
    # was: the claim quotes what the page says and asserts nothing more.
    assert evidence.evidence_type is EvidenceType.EXPERIMENTAL
    validate_claim(claim, _registry(hits)).raise_if_invalid(claim)


def test_a_claim_cannot_invent_something_the_document_does_not_say(service, workspace):
    """The document says 82%. It does not say 80 °C was a reaction temperature.

    Nothing in this stack can produce that claim, and the test exists to make
    the boundary explicit rather than to test chemistry.
    """
    parsed = ingest(service, workspace, "single.pdf", pdfs.SINGLE_PAGE)
    hits = search_document(parsed, "Yield 82%")
    quotes = " ".join(h.evidence.raw_quote for h in hits)
    assert "reaction temperature was 80" not in quotes.lower()
    # a claim built on this evidence cannot assert a temperature, because the
    # cited text does not contain one
    evidence = hits[0].evidence
    assert "80 C" in evidence.raw_quote      # the page mentions a temperature
    assert "stirred at" in evidence.raw_quote  # as an observation, not a datum


def test_the_document_is_unchanged_by_evidence_production(service, workspace):
    import copy

    parsed = ingest(service, workspace, "single.pdf", pdfs.SINGLE_PAGE)
    before = copy.deepcopy(parsed.document)
    search_document(parsed, "reagent A")
    DocumentEvidenceService().search(parsed, "reagent A")
    assert parsed.document == before


def _registry(hits):
    from crea.services.evidence import EvidenceRegistry

    registry = EvidenceRegistry()
    for hit in hits:
        registry.add(hit.evidence)
    return registry
