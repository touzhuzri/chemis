def test_A_single_page_document(service, workspace):
    parsed = ingest(service, workspace, "single.pdf", pdfs.SINGLE_PAGE)
    assert parsed.document.page_count == 1
    assert [p.page_number for p in parsed.pages] == [1]        # 1-based
