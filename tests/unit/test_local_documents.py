def test_C_a_results_heading_is_never_read_as_methods():
    """The failure this rule exists to prevent.

    "Experimental results" is a discussion of outcomes. If a detector matched
    the word, its contents would be typed `EXPERIMENTAL`, and a Claim about a
    method would be able to rest on it.
    """
    assert classify_heading("Experimental results") is None
    assert normalize_heading("Experimental results") == "experimental results"
    assert "experimental results" not in __import__(
        "crea.services.document_sections", fromlist=["_HEADINGS"])._HEADINGS


def test_C_a_sentence_is_not_a_heading():
    assert classify_heading(
        "The experimental results demonstrate a clear trend") is None


